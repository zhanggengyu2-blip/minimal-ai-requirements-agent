import { expect, test } from '@playwright/test'
test('frontend demo completes local interactions without making any API requests',async({page})=>{
  const apiRequests:string[]=[], errors:string[]=[]
  page.on('request',request=>{if(request.url().includes('/api/v1/'))apiRequests.push(request.url())})
  page.on('pageerror',error=>errors.push(error.message))
  await page.route('**/api/v1/**',route=>route.abort())
  await page.setViewportSize({width:1440,height:1000})
  await page.goto('/demo')
  await expect(page.getByRole('heading',{name:'和 Coo 一起推进工作',exact:false})).toBeVisible()
  await expect(page.getByRole('button',{name:'确认创建任务',exact:true})).toBeInViewport()
  const copy=await page.locator('.run-answer').first().evaluate(el=>({size:parseFloat(getComputedStyle(el).fontSize),color:getComputedStyle(el).color}))
  expect(copy.size).toBeGreaterThanOrEqual(16)
  expect(copy.color).toBe('rgb(31, 41, 55)')
  await page.screenshot({path:'test-results/frontend-demo-coo.png',fullPage:true})
  await page.getByRole('button',{name:'确认创建任务',exact:true}).click()
  await page.getByRole('button',{name:'打开关联任务',exact:true}).click()
  const drawer=page.getByRole('dialog',{name:'任务详情'})
  await expect(drawer).toBeVisible()
  await drawer.getByPlaceholder('记录进展，或回复同事的留言…').fill('已经联系仓库，等待反馈')
  await drawer.getByRole('button',{name:'发送留言',exact:true}).click()
  await expect(drawer.getByText('已经联系仓库，等待反馈',{exact:true})).toBeVisible()
  await drawer.getByRole('button',{name:'回复',exact:true}).click()
  await drawer.getByPlaceholder('记录进展，或回复同事的留言…').fill('预计下午同步结果')
  await drawer.getByRole('button',{name:'发送留言',exact:true}).click()
  await expect(drawer.getByText('预计下午同步结果',{exact:true})).toBeVisible()
  await page.screenshot({path:'test-results/frontend-demo-task.png',fullPage:true})
  await drawer.getByRole('button',{name:'关闭此对话框'}).click()
  await page.locator('nav').getByRole('button',{name:'主动工作'}).click()
  await page.getByRole('button',{name:'开始调查',exact:true}).click()
  const investigation=page.getByRole('dialog',{name:'调查过程与操作建议'})
  await expect(investigation.getByRole('button',{name:'确认创建任务',exact:true})).toBeVisible({timeout:10000})
  await investigation.getByRole('button',{name:'确认创建任务',exact:true}).click()
  await expect(investigation.getByText('已确认',{exact:true})).toBeVisible()
  await investigation.getByRole('button',{name:'关闭此对话框'}).click()
  await page.locator('nav').getByRole('button',{name:'知识库'}).click()
  await page.getByRole('button',{name:'召回测试',exact:true}).click()
  await page.getByRole('button',{name:'测试召回',exact:true}).click()
  await expect(page.getByText('项目知识',{exact:true})).toBeVisible()
  await page.getByRole('dialog',{name:'知识召回测试'}).getByRole('button',{name:'关闭此对话框'}).click()
  await page.locator('nav').getByRole('button',{name:'团队任务'}).click()
  await expect(page.getByRole('button').filter({hasText:'调查订单超时未发货原因'})).toHaveCount(2)
  await page.screenshot({path:'test-results/frontend-demo-board.png',fullPage:true})
  for(const name of ['需求管理','知识库','版本排期','主动工作','执行记录','Coo AI 同事']){
    await page.locator('nav').getByRole('button',{name,exact:true}).click()
    expect(await page.locator('body').innerText()).not.toMatch(/假数据|交互演示|演示|样例|预设|模拟|DEMO-/)
  }
  await page.getByRole('button',{name:'重置',exact:true}).click()
  await page.getByRole('dialog',{name:'重置工作区'}).getByRole('button',{name:'重置',exact:true}).click()
  await expect(page.getByRole('button',{name:'确认创建任务',exact:true})).toBeInViewport()
  await page.setViewportSize({width:720,height:900})
  await expect(page.getByRole('button',{name:'确认创建任务',exact:true})).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  expect(await page.locator('body').innerText()).not.toMatch(/假数据|交互演示|演示|样例|预设|模拟|DEMO-/)
  expect(apiRequests).toEqual([])
  expect(errors).toEqual([])
})
